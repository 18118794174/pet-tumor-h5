/** 按梯队分组的城市列表 */
export const cityGroups: CityGroup[] = [
  { tier: "一线城市", cities: TIER_1 },
  { tier: "准一线城市", cities: TIER_1_5 },
  { tier: "二线城市", cities: TIER_2 },
  { tier: "其他城市", cities: TIER_OTHER },
];

/** 所有城市扁平数组 */
export const allCities: string[] = cityGroups.flatMap((g) => g.cities);

/** 判断某城市是否在 hospitalsByCity 中有合作医院 */
export function hasHospitals(city: string): boolean {
  return city in hospitalsByCity;
}

/** 获取某城市的合作医院列表 */
export function getHospitalsByCity(city: string): Hospital[] {
  return hospitalsByCity[city] ?? [];
}
